def verify_checkpoint(path: str, expected_sha256: str) -> str:
    sha = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            sha.update(chunk)
    computed_hash = sha.hexdigest().upper()
    assert computed_hash == expected_sha256.upper(), f"Hash mismatch: {computed_hash} != {expected_sha256}"
    return computed_hash


def extract_historical_svg_data() -> Dict[str, Any]:
    """Parses authoritative historical SVG artifacts generated by author notebook 06."""
    svg_2b_path = "external/proteinsolver-original/docs/images/protein_analysis/191f05de-test-oneshot-incremental.svg"
    svg_2c_path = "external/proteinsolver-original/docs/images/protein_analysis/191f05de-test-incremental-kde.svg"
    
    results = {
        "svg_2b_path": svg_2b_path,
        "svg_2c_path": svg_2c_path,
        "figure_2b": {},
        "figure_2c": {}
    }
    
    if Path(svg_2b_path).exists():
        tree = ET.parse(svg_2b_path)
        root = tree.getroot()
        
        # Legend extraction
        legend_chars = []
        for elem in root.iter():
            if elem.attrib.get("id") == "legend_1":
                for child in elem.iter():
                    if "{http://www.w3.org/1999/xlink}href" in child.attrib:
                        ref = child.attrib["{http://www.w3.org/1999/xlink}href"]
                        code = int(ref.replace("#DejaVuSans-", ""))
                        legend_chars.append(chr(code))
                    elif child.tag.endswith("g") and "transform" in child.attrib and "scale" in child.attrib["transform"]:
                        legend_chars.append("\n")
        legend_str = "".join(legend_chars).strip()
        results["figure_2b"]["legend_text"] = legend_str
        
        # Extract bin counts for patch_3 (oneshot) and patch_4 (incremental)
        for p_id, mode in [("patch_3", "oneshot"), ("patch_4", "incremental")]:
            for elem in root.iter():
                if elem.attrib.get("id") == p_id:
                    for path in elem.iter():
                        d = path.attrib.get("d", "")
                        if d:
                            coords = re.findall(r"([ML])\s+([\d\.\-]+)\s+([\d\.\-]+)", d)
                            bin_counts = []
                            for i in range(1, len(coords)-1, 4):
                                top_y = float(coords[i][2])
                                height_px = 232.28 - top_y
                                count = height_px / 4.7635979
                                bin_counts.append(count)
                            results["figure_2b"][f"{mode}_bin_counts"] = bin_counts
                            results["figure_2b"][f"{mode}_total_count"] = sum(bin_counts)
                            
        results["figure_2b"]["published_headline_accuracy"] = {
            "oneshot": 0.2729,
            "incremental": 0.2680,
            "notebook_cell_36_exact": 0.2728685383656129
        }
        
    return results


