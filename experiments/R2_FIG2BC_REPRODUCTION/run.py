    fig2b_records = []
    graphs = {}
    
    for name, path, chain, desc in TARGETS:
        print(f"Loading structure {name} ({path})...")
        g = extract_protein_graph(path, chain_id=chain)
        graphs[name] = g
        seq_len = len(g.sequence)
        
        # Single-pass (oneshot)
        x_all_masked = torch.full((seq_len,), MASK_TOKEN_IDX, dtype=torch.long, device=device)
        with torch.no_grad():
            logits_oneshot = net(x_all_masked, g.edge_index.to(device), g.edge_attr.to(device))
            pred_oneshot = logits_oneshot.argmax(dim=-1).cpu()
            
        seq_oneshot = decode_indices_to_seq(pred_oneshot)
        num_correct_oneshot = int((pred_oneshot == g.x).sum().item())
        acc_oneshot = num_correct_oneshot / seq_len
        
        # Iterative MAP
        seq_iter, pred_iter, conf_iter = generate_sequence_csp(
            net, g.edge_index, g.edge_attr, seq_len, strategy="map", device=device, seed=42
        )
        num_correct_iter = int((pred_iter == g.x).sum().item())
